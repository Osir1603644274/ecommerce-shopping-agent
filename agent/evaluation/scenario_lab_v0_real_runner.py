@dataclass(frozen=True)
class PublicScenarioInput:
    """Public execution input for one scenario — never carries private truth.

    Mirrors the accepted ``ScenarioInputView`` (the runner may use either), but
    keeps the full public record available so the run can be driven and
    hashed.  The raw record is the validated public ``scenario.input.jsonl``
    record; a structural marker scan runs on load and fails closed.
    """

    scenario_id: str
    track_type: str
    schema_version: str
    catalog_revision: str
    environment_revision: str
    turns: tuple[Mapping[str, Any], ...]
    public_environment_refs: tuple[str, ...]
    setup_ref: str | None
    raw_record: Mapping[str, Any]

    @classmethod
    def from_view(cls, view: ScenarioInputView, raw_record: Mapping[str, Any]) -> "PublicScenarioInput":
        _assert_no_private_markers(raw_record, view.scenario_id)
        return cls(
            scenario_id=view.scenario_id,
            track_type=view.track_type,
            schema_version=view.schema_version,
            catalog_revision=view.catalog_revision,
            environment_revision=view.environment_revision,
            turns=tuple(view.turns),
            public_environment_refs=tuple(view.public_environment_refs),
            setup_ref=view.setup_ref,
            raw_record=dict(raw_record),
        )

    @property
    def first_message(self) -> str:
        for turn in self.turns:
            if turn.get("role") == "user" and turn.get("text"):
                return str(turn["text"])
        raise PublicInputLeakError(
            f"{self.scenario_id}: public input has no user turn text"
        )


def _walk_json(value: Any, path: str) -> Sequence[tuple[str, Any]]:
    """Yield ``(json_path, leaf)`` for every leaf in a JSON value."""
    if isinstance(value, Mapping):
        for key, child in value.items():
            yield from _walk_json(child, f"{path}.{key}")
    elif isinstance(value, (list, tuple)):
        for index, child in enumerate(value):
            yield from _walk_json(child, f"{path}[{index}]")
    else:
        yield path, value


def _assert_no_private_markers(record: Mapping[str, Any], scenario_id: str) -> None:
    """Fail closed if any key or string value in the public record carries an
    answer-face / private-truth marker (renames and casing included)."""
    # First, the accepted evaluator's own leak audit (already robust).
    try:
        audit_input_leaks(record)
    except ScenarioContractError as exc:
        raise PublicInputLeakError(
            f"{scenario_id}: public input failed the accepted leak audit: {exc}"
        ) from exc
    # Structural fields whose enum values are schema constants (validated by
    # the accepted validate_record) legitimately contain private-truth-like
    # substrings — e.g. trackType "infrastructure_fault".  They are not leaks.
    structural_fields = {
        "trackType", "schemaVersion", "catalogRevision", "environmentRevision",
        "setupRef",
    }
    # Then a structural scan over every leaf, catching markers the audit's
    # normalized substring set may allow in this context.
    for path, leaf in _walk_json(record, "input"):
        if path.rsplit(".", 1)[-1] in structural_fields:
            continue
        if isinstance(leaf, str) and _PRIVATE_TRUTH_PATH_PATTERN.search(leaf):
            raise PublicInputLeakError(
                f"{scenario_id}: public input leaf {path!r} carries a private "
                f"truth marker: {leaf!r}"
            )
        if isinstance(leaf, str):
            for marker in _FORBIDDEN_VALUE_MARKERS:
                if marker in leaf or marker.lower() in leaf.lower():
                    raise PublicInputLeakError(
                        f"{scenario_id}: public input leaf {path!r} carries "
                        f"forbidden marker {marker!r}"
                    )


def load_public_input(path: Path | str) -> list[PublicScenarioInput]:
    """Load and validate a public ``scenario.input.jsonl`` for the runner.

    Uses the accepted ``load_runner_input`` (which already rejects duplicate
    ids and applies the input schema + leak audit), then applies the
    structural marker scan above.  Returns public-only views.
    """
    records = load_jsonl(path)
    if not records:
        raise ScenarioContractError(f"{path}: input file is empty")
    views = load_runner_input(path)
    publics = [PublicScenarioInput.from_view(view, raw) for view, raw in zip(views, records, strict=True)]
    if len(publics) != len(records):
        raise ScenarioContractError(f"{path}: input view/record cardinality mismatch")
    return publics


