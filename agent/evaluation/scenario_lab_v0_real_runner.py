class RedisTaskStateDriftAdapter:
    """REAL single-step OCC revision patch (n → n+1) on a task-owned TaskState.

    REPAIR-003: identity is verified BEFORE any Redis GET/WATCH/SET.  The runner
    FIRST registers the explicit task-owned triple (``register_owned``) for a
    task it created THIS run; ``drift_revision`` then:
    * verifies task/session/thread are owned-shaped AND mutually consistent with
      the ``v2-task:<taskId>:<runId>`` thread relation (pre-Redis),
    * verifies the exact registered triple — a foreign task (even supplied with
      its real matching session) was never registered THIS run, so it is
      rejected (pre-Redis),
    * rejects a double drift and a dangling/unregistered ref (pre-Redis),
    and ONLY then performs the atomic patch with the production Lua CAS script
    (revision n → n+1 with actor/reason/hash).  The recording-fake tests prove
    every rejection performs 0 GET / 0 WATCH / 0 SET.
    """

    def __init__(self, redis_url: str | None = None, *, client: Any | None = None) -> None:
        self._redis_url = redis_url
        self._client = client  # injectable (recording fake / InFileRedis)
        self._owned: dict[str, tuple[str, str]] = {}  # task_id -> (session_id, thread_id)
        self._drifted: set[str] = set()
        self._redis_client = (
            # _patch is async and awaits get/eval.  The synchronous Redis
            # client happened to work only with the async test stand-in and
            # fails against the real service with "str can't be awaited".
            redis_async.from_url(redis_url, decode_responses=True)
            if redis_url and client is None
            else None
        )

    def _resolve_client(self) -> Any:
        if self._client is not None:
            return self._client
        if self._redis_client is None:
            raise RedisEvidenceError("drift: no Redis client configured")
        return self._redis_client

    def register_owned(self, *, task_id: str, session_id: str, thread_id: str) -> None:
        _require_owned_triple(task_id=task_id, session_id=session_id, thread_id=thread_id)
        self._owned[task_id] = (session_id, thread_id)

    def _require_owned_before_redis(
        self, *, task_id: str, session_id: str, thread_id: str
    ) -> None:
        # 1. Owned shapes + mutual v2-task relation (pre-Redis).
        _require_owned_triple(task_id=task_id, session_id=session_id, thread_id=thread_id)
        # 2. Explicit THIS-run registration.  A foreign task — even one supplied
        #    with its real matching external session — was never registered by
        #    this runner, so it is rejected BEFORE any Redis call.
        registered = self._owned.get(task_id)
        if registered is None:
            raise RedisEvidenceError(
                f"drift: task {task_id!r} was not registered THIS run "
                "(dangling ref; rejected before Redis)"
            )
        reg_session, reg_thread = registered
        if reg_session != session_id or reg_thread != thread_id:
            raise RedisEvidenceError(
                f"drift: task {task_id!r} registered under a different owned triple "
                "(session/thread mismatch; rejected before Redis)"
            )
        # 3. Single n -> n+1 only.
        if task_id in self._drifted:
            raise RedisEvidenceError(
                f"drift: task {task_id!r} already drifted (double drift; rejected before Redis)"
            )

    def drift_revision(
        self, *, task_id: str, session_id: str, thread_id: str, expected_revision: int
    ) -> DriftReceipt:
        self._require_owned_before_redis(
            task_id=task_id, session_id=session_id, thread_id=thread_id
        )
        current = asyncio.run(
            self._patch(
                task_id=task_id,
                session_id=session_id,
                thread_id=thread_id,
                expected_revision=expected_revision,
            )
        )
        self._drifted.add(task_id)
        receipt_sha = sha256_text(
            canonical_bytes(
                {
                    "taskId": task_id,
                    "sessionId": session_id,
                    "revisionBefore": current,
                    "revisionAfter": current + 1,
                    "actor": DRIFT_ACTOR,
                    "reason": DRIFT_REASON,
                }
            )
        )
        return DriftReceipt(
            task_id=task_id,
            session_id=session_id,
            revision_before=current,
            revision_after=current + 1,
            actor=DRIFT_ACTOR,
            reason=DRIFT_REASON,
            drifted_at=_iso_timestamp(),
            receipt_sha256=receipt_sha,
        )

    async def _patch(
        self, *, task_id: str, session_id: str, thread_id: str, expected_revision: int
    ) -> int:
        from app import task_state as _ts

        client = self._resolve_client()
        key = f"task-state:{task_id}"
        raw = await client.get(key)
        if not raw:
            raise RedisEvidenceError(
                f"drift: task-state missing (dangling) for {task_id!r}"
            )
        try:
            value = json.loads(raw)
        except (TypeError, json.JSONDecodeError) as exc:
            raise RedisEvidenceError(f"drift: non-JSON TaskState for {task_id!r}") from exc
        if not isinstance(value, Mapping):
            raise RedisEvidenceError(f"drift: non-object TaskState for {task_id!r}")
        if str(value.get("sessionId") or "") != session_id:
            raise RedisEvidenceError(
                f"drift: TaskState {task_id!r} owned by another session "
                "(cross-owner fail-closed)"
            )
        current = value.get("revision")
        if not isinstance(current, int):
            raise RedisEvidenceError(
                f"drift: TaskState {task_id!r} has no integer revision"
            )
        if current != expected_revision:
            raise RedisEvidenceError(
                f"drift: revision mismatch expected={expected_revision} "
                f"actual={current} (double drift or wrong expected revision; fail-closed)"
            )
        after = dict(value)
        after["revision"] = current + 1
        after["drift"] = {
            "actor": DRIFT_ACTOR,
            "reason": DRIFT_REASON,
            "revisionBefore": current,
            "revisionAfter": current + 1,
        }
        cas_result = await client.eval(
            _ts._CAS_STATE_SCRIPT,
            1,
            key,
            expected_revision,
            json.dumps(after, ensure_ascii=False, sort_keys=True),
            _ts.TASK_STATE_TTL_SECONDS,
        )
        cas_status = int(cas_result[0]) if cas_result else -2
        actual_revision = int(cas_result[1]) if cas_result and len(cas_result) > 1 else None
        if cas_status != 1:
            raise RedisEvidenceError(
                f"drift: CAS failed (concurrent revision bump) expected={expected_revision} "
                f"actual={actual_revision} (fail-closed)"
            )
        return current


