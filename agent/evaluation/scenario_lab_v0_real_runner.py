def run_scenarios(
    client_factory: Callable[[str], DurableChatClient],
    adapter: RedisEvidenceAdapter,
    mapper: ObservationMapper,
    sessions: Mapping[str, str],
    *,
    server_host: Any | None = None,
    restart_server_factory: Callable[[], Any] | None = None,
    restart_client_factory: Callable[[str], DurableChatClient] | None = None,
    fixture_receipt: FixtureReceipt | None = None,
    run_root: Path | None = None,
    base_url: str = "",
    drift_adapter: TaskStateDriftAdapter | None = None,
    keep_restart_server_alive: bool = False,
    scenarios: Sequence[ScenarioInputView] | None = None,
) -> list[dict[str, Any]]:
    """Drive the frozen scenarios in public observation order.

    INF-001 is LAST because it performs the controlled process-kill restart.
    ``server_host`` is the owned process P1 (or the test stub); when absent the
    ``drive_inf001_without_server`` fallback records the honest limitation.

    ``drift_adapter`` is the INF-004 drift machinery.  Real runs MUST pass the
    real ``RedisTaskStateDriftAdapter``; the fake in-memory adapter is used only
    when the caller (offline protocol tests) explicitly omits it.
    """
    results: list[dict[str, Any]] = []

    public_views = {
        view.scenario_id: view
        for view in (scenarios or ())
        if view.track_type == SCENARIO_TRACK_LANGUAGE
    }

    client = client_factory(sessions["lng001"])
    results.append(drive_lng001(client, adapter, mapper))
    client.close()

    client = client_factory(sessions["lng002"])
    results.append(drive_lng002(client, adapter, mapper))
    client.close()

    for index in range(3, 9):
        scenario_id = f"ASL-V0-LNG-REAL-{index:03d}"
        view = public_views.get(scenario_id)
        if view is None:
            continue
        session_key = f"lng{index:03d}"
        client = client_factory(sessions[session_key])
        results.append(drive_language_view(view, client, adapter, mapper))
        client.close()

    client = client_factory(sessions["inf002"])
    results.append(_drive_resolve_then_replay(
        "ASL-V0-INF-REAL-002", "exact_replay", client, adapter, mapper, mutated_answer=None
    ))
    client.close()

    client = client_factory(sessions["inf003"])
    results.append(_drive_resolve_then_replay(
        "ASL-V0-INF-REAL-003", "mutated_replay", client, adapter, mapper,
        mutated_answer="预算 3000 元以内，要 512GB。",
    ))
    client.close()

    if drift_adapter is None:
        drift_adapter = FakeTaskStateDriftAdapter(StubWorld())
    client = client_factory(sessions["inf004"])
    results.append(drive_inf004(client, adapter, mapper, drift_adapter=drift_adapter))
    client.close()

    # INF-001 LAST: it kills the owned server P1.  REPAIR-003: INF-001's
    # session/task/thread identity comes from the SIGNED receipt (never a
    # generated ``sessions['inf001']``); the INF-001 client, the restart client
    # and the recovery request all reuse that same receipt session.
    inf001_session = fixture_receipt.session_id if fixture_receipt is not None else sessions["inf001"]
    client1 = client_factory(inf001_session)
    if server_host is not None and restart_server_factory is not None:
        restart_server = restart_server_factory()
        results.append(drive_inf001(
            server_host, restart_server, client1, adapter, mapper, run_root or Path("."),
            fixture_receipt=fixture_receipt,
            restart_client_factory=restart_client_factory,
            keep_restart_server_alive=keep_restart_server_alive,
        ))
    else:
        results.append(drive_inf001_without_server(
            base_url, client1, adapter, mapper, inf001_session, fixture_receipt=fixture_receipt
        ))
    client1.close()

    results.sort(key=lambda r: r["scenarioId"])
    return results


