def drive_inf001_without_server(
    base_url: str,
    client1: DurableChatClient,
    adapter: RedisEvidenceAdapter,
    mapper: ObservationMapper,
    session_id: str,
    *,
    fixture_receipt: FixtureReceipt | None = None,
) -> dict[str, Any]:
    """Fallback INF-001 driver when the CLI was pointed at an external base_url
    (no owned server to kill).  Records a real request but honestly notes the
    cross-process kill could not be performed on a non-owned server."""
    r1 = _post(client1, {"message": INF_001_MESSAGE, "domainHint": "ecommerce"})
    c1 = mapper.classify(r1.body)
    identity1 = _require_task_identity(r1.body)
    if not identity1:
        return {
            "scenarioId": "ASL-V0-INF-REAL-001", "attempts": [], "taskId": "",
            "threadId": "", "runId": "", "terminalClass": "FAILURE",
            "toolCalls": mapper.build_tool_calls(r1.body), "rankedProductIds": [],
            "clarifications": [],
            "observed": {"httpStatus": r1.http_status, "note": "no task identity; cannot restart non-owned server"},
            "roundtrips": [],
        }
