class PhaseGuardError(RuntimeError):
    """Raised when a phase is invoked out of order."""


class PhaseGuard:
    """Enforces prepare? → freeze → run → score ordering.

    ``prepare`` (the checkpoint fixture phase) is optional and may be skipped
    when no real fixture can be generated.  The state lives in the run
    directory as ``.phase-stamp.json`` so a rerun cannot silently skip a phase
    or regenerate a prediction after scoring.
    """

    def __init__(self, run_dir: Path) -> None:
        self.run_dir = Path(run_dir)
        self._stamp = self.run_dir / ".phase-stamp.json"

    def _read(self) -> list[str]:
        if not self._stamp.exists():
            return []
        try:
            value = json.loads(self._stamp.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            return []
        if not isinstance(value, list):
            return []
        return [str(item) for item in value if isinstance(item, str)]

    def _write(self, phases: Sequence[str]) -> None:
        self._stamp.parent.mkdir(parents=True, exist_ok=True)
        self._stamp.write_text(
            json.dumps(list(phases), ensure_ascii=False, sort_keys=True),
            encoding="utf-8",
        )

    def assert_can(self, phase: str) -> None:
        done = self._read()
        order = ("prepare", "freeze", "run", "score")
        phase_index = order.index(phase)
        # Any later phase already done refuses an earlier/duplicate phase.
        for earlier in order:
            if earlier in done and order.index(earlier) > phase_index:
                raise PhaseGuardError(
                    f"cannot run phase {phase!r}: {earlier!r} already completed "
                    f"(order must be prepare? → freeze → run → score; prepare optional)"
                )
        if phase in done:
            raise PhaseGuardError(
                f"phase {phase!r} already completed; refusing to repeat it"
            )

    def mark(self, phase: str) -> None:
        done = self._read()
        if phase not in done:
            done.append(phase)
            self._write(done)

    @property
    def phases_done(self) -> list[str]:
        return self._read()


def write_jsonl_atomic(path: Path | str, records: Sequence[Mapping[str, Any]]) -> Path:
    """Write JSONL atomically (tmp + rename) into the run's own directory."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    with open(tmp, "w", encoding="utf-8") as fh:
        for record in records:
            fh.write(json.dumps(record, ensure_ascii=False, sort_keys=False, separators=(",", ":")))
            fh.write("\n")
    os.replace(tmp, path)
    return path


def write_json_atomic(path: Path | str, value: Mapping[str, Any]) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
