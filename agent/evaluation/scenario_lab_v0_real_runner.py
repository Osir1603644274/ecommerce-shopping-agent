class DurableClientError(RuntimeError):
    """Raised when the durable endpoint is unreachable or returns a transport
    failure — a real dependency blocker, never a mocked success."""


@dataclass(frozen=True)
class DurableResponse:
    """One real HTTP round-trip against /agent/chat-llm-durable."""

    request_id: str
    http_status: int
    body: dict[str, Any] | None
    request_body: Mapping[str, Any]
    raw_request_bytes: bytes
    raw_response_bytes: bytes
    error: str | None = None
    duration_ms: float = 0.0

    @property
    def ok(self) -> bool:
        return self.body is not None and self.error is None

    @property
    def payload_sha256(self) -> str:
        # ``raw_request_bytes`` are ALREADY canonical bytes (the exact payload
        # sent on the wire) — hash them directly; canonical_bytes() expects a
        # JSON-serializable structure, not bytes.
        return sha256_text(self.raw_request_bytes)

    @property
    def result_sha256(self) -> str:
        return sha256_text(self.raw_response_bytes)


class DurableChatClient:
    """Thin HTTP client for the durable control-plane endpoint.

    The client preserves the exact request and response bytes so the
    observation mapper hashes what was actually sent and received.  It never
    inspects private files and never fabricates a response.
    """

    def __init__(self, base_url: str, session_id: str, *, timeout_seconds: float = 65.0) -> None:
        if not session_id or len(session_id) > MAX_SESSION_ID_LENGTH:
            raise ValueError(
                f"sessionId must be 1..{MAX_SESSION_ID_LENGTH} chars, got {len(session_id)!r}"
            )
        self.base_url = base_url.rstrip("/")
        self.session_id = session_id
        self.timeout_seconds = timeout_seconds
        self._client: Any = None

    def _http(self) -> Any:
        if self._client is None:
            import httpx

            self._client = httpx.Client(timeout=self.timeout_seconds, follow_redirects=False)
        return self._client

    def close(self) -> None:
        if self._client is not None:
            try:
                self._client.close()
            except Exception:  # noqa: BLE001
                pass
            self._client = None

    def health(self) -> tuple[bool, int]:
        # FastAPI serves /docs (OpenAPI HTML) on every app; the repo has no
        # dedicated /health route, so /docs is the honest liveness probe.
        try:
            response = self._http().get(f"{self.base_url}/docs")
            return response.status_code < 500, response.status_code
        except Exception as exc:  # noqa: BLE001 - transport failure is a blocker
            raise DurableClientError(f"health probe failed: {type(exc).__name__}: {exc}") from exc

    def post(self, payload: Mapping[str, Any]) -> DurableResponse:
        body = dict(payload)
        if not body.get("sessionId"):
            body["sessionId"] = self.session_id
        request_bytes = canonical_bytes(body)
        start = time.perf_counter()
        try:
            response = self._http().post(
                f"{self.base_url}/agent/chat-llm-durable",
                content=request_bytes,
                headers={"Content-Type": "application/json"},
            )
        except Exception as exc:  # noqa: BLE001
            raise DurableClientError(
                f"durable request failed: {type(exc).__name__}: {exc}"
            ) from exc
        duration_ms = (time.perf_counter() - start) * 1000.0
        raw = response.content
        body_value: dict[str, Any] | None = None
        error: str | None = None
        if raw:
            try:
                parsed = json.loads(raw.decode("utf-8"))
                body_value = parsed if isinstance(parsed, dict) else None
            except (UnicodeDecodeError, json.JSONDecodeError) as exc:
                error = f"non-JSON response: {type(exc).__name__}: {exc}"
        request_id = ""
        if body_value is not None:
            trace = body_value.get("trace") or {}
            request_id = str(trace.get("requestId") or "") if isinstance(trace, Mapping) else ""
        return DurableResponse(
            request_id=request_id,
            http_status=response.status_code,
            body=body_value,
            request_body=body,
            raw_request_bytes=request_bytes,
            raw_response_bytes=raw,
            error=error,
            duration_ms=duration_ms,
        )


