    """Shared explicit identity-failure result for INF-001 (REPAIR-004 Repair 1c
    + REPAIR-005 Repair 3): attempts=[], empty ids, FAILURE terminal, and NO
    kill / restart / second request / recovery ref.  Exactly 1 request occurred."""
