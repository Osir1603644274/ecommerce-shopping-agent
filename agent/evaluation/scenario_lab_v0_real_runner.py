def probe_http(
    url: str,
    *,
    method: str = "GET",
    payload: Mapping[str, Any] | None = None,
    timeout: float = 3.0,
    kind: str = "",
) -> dict[str, Any]:
    """One structural HTTP probe that CAPTURES the response body exactly once.

    Records reachable/status/error/latency/timestamp AND, when ``kind`` names a
    semantic endpoint (catalog / retrieval-smoke / index / backend / control),
    parses that single captured body into kind-derived fields.  Every
    dependency conclusion in this module is derived from the fields of ONE
    captured response — never a probe-then-second-request race.
    """
    import httpx

    result: dict[str, Any] = {
        "url": url,
        "method": method,
        "kind": kind,
        "reachable": False,
        "httpStatus": None,
        "errorType": None,
        "latencyMs": None,
        "timestamp": _iso_timestamp(),
        "source": "probe_http",
    }
    start = time.perf_counter()
    try:
        if method == "GET":
            response = httpx.get(url, timeout=timeout)
        else:
            response = httpx.post(url, json=payload or {}, timeout=timeout)
        result["reachable"] = response.status_code < 500
        result["httpStatus"] = response.status_code
        result["latencyMs"] = round((time.perf_counter() - start) * 1000.0, 1)
        data: Any = None
        try:
            data = response.json()
        except Exception:  # noqa: BLE001 - unparsable body is honest evidence
            pass
        _derive_kind_evidence(result, kind, data)
    except Exception as exc:  # noqa: BLE001 - transport failure IS the evidence
        result["errorType"] = type(exc).__name__
        result["latencyMs"] = round((time.perf_counter() - start) * 1000.0, 1)
    return result


def _count_items(data: Any) -> int | None:
    """Item count from a captured catalog/retrieval body (single source)."""
    if isinstance(data, list):
        return len(data)
    if isinstance(data, Mapping):
        for key in ("data", "products", "items", "docs", "results"):
            value = data.get(key)
            if isinstance(value, list):
                return len(value)
            if isinstance(value, Mapping):
                if isinstance(value.get("total"), int):
                    return value["total"]
                # The production retrieval response is an ApiResponse envelope:
                # {"data": {"products": [...]}}.  Recurse only through the
                # small allowlisted response-container keys above so arbitrary
                # unrelated arrays cannot satisfy the semantic probe.
                nested = _count_items(value)
                if nested is not None:
                    return nested
    return None


def _derive_kind_evidence(result: dict[str, Any], kind: str, data: Any) -> None:
    """Derive per-kind semantic fields from the ONE captured response body.

    Each conclusion reuses the captured response — there is no second request.
    A field that cannot be derived honestly stays absent/false (fail closed).
    """
    if kind == "catalog":
        count = _count_items(data)
        result["catalogDocCount"] = count
        result["catalogParsed"] = count is not None
    elif kind == "retrieval-smoke":
        count = _count_items(data)
        result["retrievedCount"] = count
        result["retrievalParsed"] = count is not None
    elif kind == "index":
        if isinstance(data, Mapping):
            status = data.get("status")
            result["esStatus"] = status if isinstance(status, str) else None
            result["esHealthParsed"] = result["esStatus"] in ("green", "yellow", "red")
            nodes = data.get("number_of_nodes")
            result["esNumberOfNodes"] = nodes if isinstance(nodes, int) else None
    elif kind in ("backend", "control", "control-plane"):
        if isinstance(data, Mapping) and isinstance(data.get("status"), str):
            result["healthStatus"] = data.get("status")
            result["healthParsed"] = True
        elif isinstance(data, Mapping):
            result["healthParsed"] = False
        # The task-owned Agent /health MAY expose its ACTUAL retrieval mode and
        # ES-active status; when present they are reconciled by the read-back.
        if isinstance(data, Mapping):
            mode = data.get("retrievalMode")
            if isinstance(mode, str):
                result["retrievalMode"] = mode
            es = data.get("esStatus")
            if not isinstance(es, str) and isinstance(data.get("elasticsearch"), Mapping):
                es = data["elasticsearch"].get("status")
            if isinstance(es, str):
                result["esStatus"] = es
            # REPAIR-004: the live Agent /health exposes the process's ACTUALLY
            # loaded non-secret retrieval config (backendBaseUrl +
            # productRetrievalMode); captured here from the observed body (never
            # echoed from configuration) for the read-back's exact reconciliation.
            backend_loaded = data.get("backendBaseUrl")
            if isinstance(backend_loaded, str):
                result["backendBaseUrl"] = backend_loaded
            mode_loaded = data.get("productRetrievalMode")
            if isinstance(mode_loaded, str):
                result["productRetrievalMode"] = mode_loaded


def derive_retrieval_chain(targets: Mapping[str, Any]) -> bool:
    """Pure derivation: the real retrieval chain is UP only when EVERY semantic
    requirement holds on the CAPTURED probe responses:

    * search-Java readiness parsed and status == "UP";
    * search-Java catalog parsed and catalogDocCount == 252 (exactly);
    * retrieval smoke parsed and retrievedCount > 0 (non-empty);
    * Elasticsearch health parsed and status not "red";
    * Redis (when probed) reachable.

    A 404, an empty 200, wrong JSON, a 251/253 catalog, an empty retrieval
    result or a red ES all fail closed.  Each conclusion reuses ONE captured
    response — never a probe-then-second-request race.
    """
    if not isinstance(targets, Mapping):
        return False

    def _entry(name: str) -> Mapping[str, Any]:
        value = targets.get(name)
        return value if isinstance(value, Mapping) else {}

    readiness = _entry("searchJavaReadiness")
    if not (
        bool(readiness.get("reachable"))
        and bool(readiness.get("healthParsed"))
        and readiness.get("healthStatus") == "UP"
    ):
        return False

    catalog = _entry("searchJavaCatalog")
    if not (
        bool(catalog.get("reachable"))
        and bool(catalog.get("catalogParsed"))
        and catalog.get("catalogDocCount") == CATALOG_EXPECTED_COUNT
    ):
        return False

    retrieval = _entry("retrievalSmoke")
    if not (
        bool(retrieval.get("reachable"))
        and bool(retrieval.get("retrievalParsed"))
        and int(retrieval.get("retrievedCount") or 0) > 0
    ):
        return False

    es = _entry("elasticsearch")
    if not (
        bool(es.get("reachable"))
        and bool(es.get("esHealthParsed"))
        and es.get("esStatus") not in ("red", None)
    ):
        return False

    redis_entry = _entry("redis")
    if redis_entry and not bool(redis_entry.get("reachable")):
        return False

    return True


def preflight_probe(
    *,
    targets: Sequence[BackendProbeTarget] | None = None,
    redis_url: str | None = None,
    app_base_url: str | None = None,
) -> dict[str, Any]:
    """Probe the real chain and record STRUCTURAL evidence per target.

    Targets probed: search Java :18082 (readiness + catalog-252 + retrieval
    smoke), Elasticsearch :19281, benchmark Java :18081, Redis, and the durable
    app.  Each probe captures its response body ONCE; ``derive_retrieval_chain``
    is a pure function of the captured evidence — never a hardcoded conclusion
    and never a probe-then-second-request race.
    """
    evidence: dict[str, Any] = {"targets": {}, "derived": {}}
    for target in targets or DEFAULT_PROBE_TARGETS:
        probe = probe_http(
            target.url,
            method=target.method,
            payload=target.payload,
            timeout=target.timeout_seconds,
            kind=target.kind,
        )
        probe["name"] = target.name
        evidence["targets"][target.name] = probe
    if redis_url:
        adapter = RedisEvidenceAdapter(redis_url)
        ping = adapter.ping()
        adapter.close()
        evidence["targets"]["redis"] = {
            "name": "redis",
            "kind": "store",
            "url": redis_url,
            "reachable": ping,
            "httpStatus": None,
            "errorType": None if ping else "ping-failed",
            "latencyMs": None,
            "timestamp": _iso_timestamp(),
            "source": "RedisEvidenceAdapter.ping",
        }
    if app_base_url:
        probe = probe_http(f"{app_base_url.rstrip('/')}/health", timeout=3.0, kind="control-plane")
        probe["name"] = "durableApp"
        evidence["targets"]["durableApp"] = probe
    evidence["derived"]["retrievalChainUp"] = derive_retrieval_chain(evidence["targets"])
    evidence["derived"]["backendBaseUrl"] = SEARCH_JAVA_BASE_URL
    evidence["derived"]["probeDate"] = _iso_timestamp()
    return evidence


def verify_active_backend(probe: Mapping[str, Any], *, base_url: str, redis_url: str | None = None) -> bool:
    """Cross-check that the RUN's configured backend base_url is EXACTLY the
    probed search-Java chain AND the chain is actually reachable.

    Returns True only when: (a) the retrieval chain probe says UP (semantically:
    catalog==252, retrieval non-empty, ES not red), (b) the configured backend
    URL equals the probed chain (not ``localhost:8080``), and (c) Redis (when
    supplied) is reachable.  The caller fails closed on any False.
    """
    if not isinstance(probe, Mapping):
        return False
    targets = probe.get("targets")
    if not isinstance(targets, Mapping):
        return False
    derived = probe.get("derived")
    if not isinstance(derived, Mapping):
        return False
    if not bool(derived.get("retrievalChainUp")):
        return False
    configured = str(derived.get("backendBaseUrl") or "").rstrip("/")
    if configured != str(base_url or "").rstrip("/"):
        return False
    if redis_url:
        redis_entry = targets.get("redis") or {}
        if not bool(redis_entry.get("reachable")):
            return False
    return True


