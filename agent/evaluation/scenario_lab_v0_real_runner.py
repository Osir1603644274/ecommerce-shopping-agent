class StubEvidenceAdapter:
    """Test-only read-only evidence adapter backed by StubWorld.

    Implements the same surface the drivers use on ``RedisEvidenceAdapter``
    (task_revision / checkpoint_count / latest_checkpoint / task_snapshot) over
    the in-memory world.  Never claimed as a real Redis adapter.
    """

    def __init__(self, world: StubWorld) -> None:
        self._world = world

    def close(self) -> None:
        pass

    def task_revision(self, task_id: str) -> int | None:
        state = self._world.tasks.get(task_id)
        if state is None:
            return None
        return state.get("revision") if isinstance(state.get("revision"), int) else None

    def checkpoint_count(self, thread_id: str) -> int:
        return 1 if thread_id in self._world.checkpoints else 0

    def latest_checkpoint(self, thread_id: str) -> tuple[str | None, str | None]:
        cp = self._world.checkpoints.get(thread_id)
        if cp is None:
            return None, None
        return cp["ref"], cp["sha"]

    def task_snapshot(self, task_id: str) -> dict[str, Any] | None:
        state = self._world.tasks.get(task_id)
        if state is None:
            return None
        return {key: value for key, value in state.items() if key in {"taskId", "sessionId", "status", "revision"}}

    def read_owned_thread(self, task_id: str, run_id: str, *, session_id: str) -> str | None:
        """REPAIR-005 Repair 3 (stub): read-back the server-owned persisted
        thread from the world's TaskState domainState.v2RunMarker.  The
        ``inf001_thread_missing`` / ``inf001_thread_drift`` modes simulate the
        server persisting NO matching marker or a drifted one."""
        if getattr(self._world, "inf001_thread_missing", False):
            return None
        if getattr(self._world, "inf001_thread_drift", False):
            return f"v2-task:{TASK_OWNED_SESSION_PREFIX}-drifted-thread:run-drifted"
        state = self._world.tasks.get(task_id)
        if state is None:
            return None
        domain = state.get("domainState")
        if not isinstance(domain, Mapping):
            return None
        marker = domain.get("v2RunMarker")
        if not isinstance(marker, Mapping):
            return None
        if str(marker.get("runId") or "") != run_id:
            return None
        thread = str(marker.get("threadId") or "")
        if thread != f"v2-task:{task_id}:{run_id}":
            return None
        return thread


