def _pick(mapping: Mapping[str, Any], *keys: str) -> Any:
    """First non-None value among keys (alias-first, field-name fallback)."""
    for key in keys:
        if key in mapping and mapping[key] is not None:
            return mapping[key]
    return None


def normalize_body(body: dict[str, Any] | None) -> dict[str, Any]:
    """Return a canonical view of a real durable response.

    The server's ``ChatResponse`` model serializes aliases by default
    (``runId``/``traceSummary``/``taskState``/``guideResult``), while earlier
    responses used the python field names (``run_id``/``trace_summary``/...).
    This helper accepts both spellings so the mapper is stable across the
    server's serialization choices.  It never invents fields.
    """
    if not body:
        return {}
    return {
        "answer": _pick(body, "answer") or "",
        "tool_trace": _pick(body, "tool_trace") or [],
        "trace": _pick(body, "trace") or {},
        "request_id": _pick(body, "requestId", "request_id") or "",
        "run_id": _pick(body, "runId", "run_id"),
        "trace_summary": _pick(body, "traceSummary", "trace_summary"),
        "task_state": _pick(body, "taskState", "task_state"),
        "guide_result": _pick(body, "guideResult", "guide_result"),
        "task_relation": _pick(body, "taskRelation", "task_relation"),
        "_raw": body,
    }


class ObservationMapper:
    """Maps real observations to schema-valid prediction attempts.

    Nothing here knows oracle/fault truth.  Every count/hash/identity comes
    from the real HTTP response or the read-only Redis evidence adapter.
    """

    def __init__(self, session_id: str) -> None:
        self.session_id = session_id

    # -- classification ------------------------------------------------------

    def classify(self, body: dict[str, Any] | None, *, task_id: str | None = None) -> ClassifiedResponse:
        if body is None:
            return ClassifiedResponse(
                terminal_code="FAILURE", rejected=False, rejection_code=None,
                tool_calls=0, model_calls=0, final_action=None, agent_status=None,
                degraded=False, failure_code=None, request_id="", task_id=task_id,
                thread_id=None, run_id=None, revision_after=None, phases=(),
            )
        norm = normalize_body(body)
        trace = norm["trace"] or {}
        trace_status = trace.get("status")
        ts = norm["trace_summary"] or {}
        if not isinstance(ts, Mapping):
            ts = {}
        final_action = ts.get("finalAction") or trace.get("agentFinalAction")
        agent_status = ts.get("agentStatus") or trace.get("agentStatus")
        degraded = bool(ts.get("degraded"))
        failure_code = ts.get("failureCode") or trace.get("agentFailureCode")
        phases = tuple(str(item.get("phase")) for item in (ts.get("phases") or []) if isinstance(item, Mapping))
        # TraceSummary serializes ``tool_call_count`` by field name (no alias).
        tool_calls = int(ts.get("tool_call_count") or 0)
        model_calls = sum(1 for phase in phases if phase in MODEL_INVOKING_PHASES)
        request_id = str(norm["request_id"] or trace.get("requestId") or "")
        run_id = norm["run_id"] or trace.get("runId")
        task_state = norm["task_state"]
        task_id_obs = None
        revision_after = None
        if isinstance(task_state, Mapping):
            task_id_obs = task_state.get("taskId")
            rev = task_state.get("revision")
            if isinstance(rev, int):
                revision_after = rev

        # Ownership rejection / durable-disabled / missing-api-key responses
        # carry no trace_summary.
        if not ts and isinstance(norm["answer"], str):
            if norm["answer"] == _OWNERSHIP_REJECTED_ANSWER or trace_status == "error":
                return ClassifiedResponse(
                    terminal_code="ABSTAIN_OR_EXPLAIN", rejected=True,
                    rejection_code="durable_session_ownership_rejected",
                    tool_calls=0, model_calls=0, final_action=final_action,
                    agent_status=agent_status, degraded=degraded,
                    failure_code=failure_code, request_id=request_id,
                    task_id=task_id_obs, thread_id=None, run_id=run_id,
                    revision_after=revision_after, phases=phases,
                )

        terminal = _FINAL_ACTION_TERMINAL.get(final_action or "")
        rejected = final_action in {"resume_rejected", "state_diverged", "safe_stop"}
        if final_action == "idempotent_resume_replay":
            # An exact replay resolves to the ALREADY-resolved task terminal.
            # The caller supplies the referenced terminal explicitly (it is the
            # terminal of the baseline resolved resume); leave a placeholder
            # here so build_attempt substitutes the referenced value.
            terminal = ""
        elif not terminal:
            if agent_status == "failed":
                terminal = "FAILURE"
            elif degraded:
                terminal = "ABSTAIN_OR_EXPLAIN"
            else:
                terminal = "FAILURE"
        return ClassifiedResponse(
            terminal_code=terminal,
            rejected=rejected,
            rejection_code=None,
            tool_calls=tool_calls,
            model_calls=model_calls,
            final_action=final_action,
            agent_status=agent_status,
            degraded=degraded,
            failure_code=failure_code,
            request_id=request_id,
            task_id=task_id_obs,
            thread_id=(
                f"v2-task:{task_id_obs}:{run_id}"
                if task_id_obs and run_id
                else None
            ),
            run_id=run_id,
            revision_after=revision_after,
            phases=phases,
        )

    # -- evidence snapshots ----------------------------------------------------

    def snapshot(self, adapter: RedisEvidenceAdapter, *, task_id: str, thread_id: str) -> dict[str, Any]:
        return {
            "revision": adapter.task_revision(task_id),
            "checkpointCount": adapter.checkpoint_count(thread_id) if thread_id else 0,
            "checkpointRef": adapter.latest_checkpoint(thread_id)[0] if thread_id else None,
            "checkpointSha256": adapter.latest_checkpoint(thread_id)[1] if thread_id else None,
            "taskState": adapter.task_snapshot(task_id) if task_id else None,
        }

    # -- attempt construction --------------------------------------------------

    def build_attempt(
        self,
        *,
        attempt_kind: str,
        classified: ClassifiedResponse,
        request: DurableResponse,
        payload_sha256: str,
        result_sha256: str,
        snapshot_before: dict[str, Any],
        snapshot_after: dict[str, Any],
        thread_id: str,
        rejection_reason_hint: str | None = None,
        referenced_terminal: str | None = None,
    ) -> dict[str, Any]:
        """Build one schema-valid attempt dict from REAL observations."""
        attempt: dict[str, Any] = {
            "attemptKind": attempt_kind,
            "requestId": classified.request_id or request.request_id,
            "runId": classified.run_id or "",
            "taskId": classified.task_id or "",
            "threadId": thread_id or classified.thread_id or "",
            "payloadSha256": payload_sha256,
            "resultSha256": result_sha256,
            "toolCalls": classified.tool_calls,
            "modelCalls": classified.model_calls,
        }
        rev_before = snapshot_before.get("revision")
        rev_after = snapshot_after.get("revision")
        if isinstance(rev_before, int):
            attempt["revisionBefore"] = rev_before
        if isinstance(rev_after, int):
            attempt["revisionAfter"] = rev_after
        h_before = snapshot_before.get("checkpointCount")
        h_after = snapshot_after.get("checkpointCount")
        if isinstance(h_before, int):
            attempt["historyCountBefore"] = h_before
        if isinstance(h_after, int):
            attempt["historyCountAfter"] = h_after
        checkpoint_ref = snapshot_after.get("checkpointRef")
        checkpoint_sha = snapshot_after.get("checkpointSha256")
        if checkpoint_ref:
            attempt["checkpointRef"] = str(checkpoint_ref)
        if checkpoint_sha:
            attempt["checkpointSha256"] = str(checkpoint_sha)

        terminal = classified.terminal_code
        if classified.final_action == "idempotent_resume_replay":
            terminal = referenced_terminal or ""
        if terminal:
            attempt["terminalCode"] = terminal
        if classified.rejected:
            attempt["rejected"] = True
        # Attach a rejection code ONLY when the observed response confirms the
        # fail-closed pattern AND a deterministic server reason exists for the
        # deliberately-crafted mutation.  Disclosed in the manifest.
        if classified.rejected and rejection_reason_hint:
            reason = REJECTION_REASON_BY_MUTATION.get(rejection_reason_hint)
            if reason:
                attempt["rejectionCode"] = reason
        elif classified.rejected and classified.final_action == "resume_rejected":
            # A rejection with no dedicated code from the response still has a
            # terminal code; keep it so the scorer's conflict gate sees it.
            attempt["terminalCode"] = attempt.get("terminalCode") or "ABSTAIN_OR_EXPLAIN"
        return attempt

    def build_tool_calls(self, body: dict[str, Any] | None) -> list[dict[str, Any]]:
        norm = normalize_body(body)
        calls: list[dict[str, Any]] = []
        for index, trace in enumerate(norm["tool_trace"] or []):
            if not isinstance(trace, Mapping):
                continue
            name = _pick(trace, "tool_name", "tool") or trace.get("toolName")
            if not name:
                continue
            ok = _pick(trace, "ok", "toolOk")
            calls.append(
                {
                    "toolName": str(name),
                    "ok": bool(ok),
                    "turnIndex": index,
                }
            )
        return calls

    @staticmethod
    def _collect_product_ids(value: Any) -> list[str]:
        """Collect real product ids from the actual server response.

        Walks the normalized response JSON (guideResult cards, trace, TaskState)
        and gathers every server-owned product identifier: ``productId`` /
        ``product_id`` leaves, ``selected_product_ids``/``selectedProductIds``
        lists, ``rankedFinalists`` entries, and ``product`` objects with ``id``.
        The response is real; the collector never invents ids and never reads
        the private oracle.
        """
        found: list[str] = []
        seen: set[str] = set()

        def emit(pid: Any) -> None:
            if pid is None:
                return
            text = str(pid)
            if text and text not in seen:
                seen.add(text)
                found.append(text)

        def walk(node: Any, key: str | None = None) -> None:
            if isinstance(node, Mapping):
                if key in {"productId", "product_id", "id"} and node.get("productId") is not None:
                    emit(node.get("productId"))
                    return
                for child_key, child in node.items():
                    if child_key in {"productId", "product_id"}:
                        emit(child)
                        continue
                    if child_key in {"selected_product_ids", "selectedProductIds", "rankedFinalists",
                                     "productPresentations"}:
                        if isinstance(child, list):
                            for item in child:
                                if isinstance(item, Mapping):
                                    emit(item.get("productId") or item.get("product_id") or item.get("id"))
                                else:
                                    emit(item)
                        continue
                    if child_key == "product" and isinstance(child, Mapping):
                        emit(child.get("id") or child.get("productId"))
                        continue
                    if child_key in {"evidenceRefs", "sources", "review_ids"}:
                        continue
                    walk(child, child_key)
            elif isinstance(node, list):
                for item in node:
                    walk(item, key)

        walk(value)
        return found

    def build_ranked(self, body: dict[str, Any] | None) -> list[str]:
        """Read only the server-published ordered ranking.

        A response also contains the retrieval candidate pool and evidence
        objects. Walking the whole envelope turns eliminated/unpublished IDs
        into recommendations, so the runner prefers Validator-published cards
        and uses an explicit ranked-list fallback only for older wire shapes.
        """
        guide = normalize_body(body).get("guide_result")
        if not isinstance(guide, Mapping):
            return []

        products = guide.get("products")
        if isinstance(products, list):
            ranked: list[str] = []
            for item in products:
                if not isinstance(item, Mapping):
                    continue
                product = item.get("product")
                product_id = product.get("id") if isinstance(product, Mapping) else None
                if product_id is not None and str(product_id) not in ranked:
                    ranked.append(str(product_id))
            if ranked:
                return ranked

        def first_explicit_ranking(node: Any) -> list[str]:
            if isinstance(node, Mapping):
                for key in (
                    "selected_product_ids", "selectedProductIds", "rankedItemIds",
                ):
                    values = node.get(key)
                    if isinstance(values, list) and values:
                        return list(dict.fromkeys(str(value) for value in values))
                for child in node.values():
                    found = first_explicit_ranking(child)
                    if found:
                        return found
            elif isinstance(node, list):
                for child in node:
                    found = first_explicit_ranking(child)
                    if found:
                        return found
            return []

        return first_explicit_ranking(guide)

    def build_claimed_constraints(
        self, body: dict[str, Any] | None,
    ) -> dict[str, list[dict[str, Any]]] | None:
        """Project public TaskState brand constraints into scorer atoms."""
        task_state = normalize_body(body).get("task_state")
        if not isinstance(task_state, Mapping):
            return None
        domain = _pick(task_state, "domainState", "domain_state")
        guide = domain.get("shoppingGuide") if isinstance(domain, Mapping) else None
        if not isinstance(guide, Mapping):
            return None

        brand_labels = {
            "apple": "苹果/apple",
            "samsung": "三星/samsung",
            "huawei": "华为/huawei",
            "honor": "荣耀/honor",
            "xiaomi": "小米/xiaomi",
            "redmi": "红米/redmi",
            "oppo": "OPPO/oppo",
            "vivo": "vivo",
            "iqoo": "iQOO/iqoo",
        }

        def labels(value: Any) -> list[str]:
            values = value if isinstance(value, list) else [value]
            return list(dict.fromkeys(
                brand_labels.get(str(item).casefold(), str(item))
                for item in values
                if item is not None and str(item)
            ))

        groups: dict[str, list[dict[str, Any]]] = {"hard": [], "soft": []}
        for requirement in guide.get("requirements") or []:
            if not isinstance(requirement, Mapping) or requirement.get("key") != "brand":
                continue
            operator = str(requirement.get("operator") or "").casefold()
            if operator not in {"eq", "in", "not_in"}:
                continue
            atom = {
                "group": "brand",
                "operator": "NOT_IN" if operator == "not_in" else "IN",
                "allowedValues": labels(requirement.get("value")),
            }
            priority = str(requirement.get("priority") or "hard").casefold()
            if atom["allowedValues"] and atom not in groups.get(priority, groups["hard"]):
                groups.get(priority, groups["hard"]).append(atom)
        for avoidance in guide.get("brandAvoidances") or []:
            if not isinstance(avoidance, Mapping):
                continue
            atom = {
                "group": "brand",
                "operator": "NOT_IN",
                "allowedValues": labels(avoidance.get("values")),
            }
            priority = str(avoidance.get("strength") or "hard").casefold()
            target = groups.get(priority, groups["hard"])
            if atom["allowedValues"] and atom not in target:
                target.append(atom)
        return groups if groups["hard"] or groups["soft"] else None

    def result_hash(
        self,
        body: dict[str, Any] | None,
        classified: ClassifiedResponse,
        *,
        terminal_override: str | None = None,
    ) -> str:
        """Canonical SHA-256 of the observed RESULT, not the raw HTTP envelope.

        Byte-equality of full envelopes is impossible (requestId/timestamps),
        so exact-replay proof is defined over the semantic result the server
        returned: answer + server-owned identity + terminal/rejection outcome.
        Identical requests produce identical payloadSha256; identical semantic
        results produce identical resultSha256.  Disclosed in the manifest.

        ``terminal_override`` lets an idempotent replay hash against the
        referenced (already-resolved) terminal instead of the empty placeholder
        the classifier emits, so baseline and replay hashes can actually match.
        """
        terminal = terminal_override if terminal_override else classified.terminal_code
        normalized = normalize_body(body)
        result = {
            # Missing/non-ChatResponse HTTP bodies remain observed failures;
            # they must not crash the runner itself with a KeyError.
            "answer": str(normalized.get("answer") or ""),
            "taskId": classified.task_id or "",
            "threadId": classified.thread_id or "",
            "runId": classified.run_id or "",
            "terminalCode": terminal,
            "rejected": classified.rejected,
            "rejectionCode": classified.rejection_code or "",
        }
        return sha256_text(canonical_bytes(result))

    def build_clarifications(self, body: dict[str, Any] | None) -> list[dict[str, Any]]:
        """Capture server-owned clarification questions from the response's
        TaskState pendingQuestions (one entry per pending question)."""
        norm = normalize_body(body)
        task_state = norm.get("task_state")
        questions = []
        if isinstance(task_state, Mapping):
            for index, question in enumerate(task_state.get("pendingQuestions") or []):
                if isinstance(question, str) and question:
                    questions.append({"question": question, "turnIndex": index})
        return questions


