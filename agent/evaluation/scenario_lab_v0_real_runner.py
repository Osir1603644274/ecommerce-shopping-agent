class RedisEvidenceError(RuntimeError):
    """Raised when the read-only evidence adapter is asked to do something
    unsafe or unavailable."""


class RedisEvidenceAdapter:
    """Strictly read-only evidence reader for task-owned plain-Redis state.

    Safety contract (TASK_PACKET Runtime ownership):

    * It exposes NO write method (no set/del/hset/flush/scan-and-delete).
    * Every key is guarded by ``_require_owned_key``: only keys under
      ``TASK_OWNED_KEY_PREFIXES`` are readable; anything else is refused.
    * Trace records additionally require the record's taskId/sessionId to
      match the owned identity the runner supplies, so a guessed run_id can
      never disclose another session's trace.
    * Reads return REDACTED projections/hashes only — raw TaskState facts,
      prompts and payloads are never written to the manifest.
    """

    def __init__(self, redis_url: str, *, client: Any | None = None) -> None:
        # REPAIR-004: ``client`` is a test-only injection point so recording
        # fakes can prove zero-I/O fail-closed rejection; production always
        # constructs the read-only sync redis client from the URL.
        self._client = client if client is not None else redis.from_url(
            redis_url, decode_responses=True
        )

    def close(self) -> None:
        try:
            self._client.close()
        except Exception:  # noqa: BLE001 - best effort
            pass

    def ping(self) -> bool:
        try:
            return bool(self._client.ping())
        except Exception:  # noqa: BLE001 - unreachable Redis is a dependency blocker
            return False

    # -- guard ---------------------------------------------------------------

    def _require_owned_key(self, key: str, *, owner_scope: str | None = None) -> str:
        if not isinstance(key, str) or not key:
            raise RedisEvidenceError("refusing empty Redis key")
        if not key.startswith(TASK_OWNED_KEY_PREFIXES):
            raise RedisEvidenceError(
                f"refusing non-task-owned Redis key {key!r} (owned prefixes: "
                f"{', '.join(TASK_OWNED_KEY_PREFIXES)})"
            )
        if owner_scope is not None and owner_scope not in key:
            raise RedisEvidenceError(
                f"refusing Redis key {key!r} outside owned scope {owner_scope!r}"
            )
        return key

    # -- task state ----------------------------------------------------------

    def task_revision(self, task_id: str) -> int | None:
        key = self._require_owned_key(f"task-state:{task_id}", owner_scope=task_id)
        raw = self._client.get(key)
        if not raw:
            return None
        try:
            value = json.loads(raw)
        except (TypeError, json.JSONDecodeError):
            return None
        revision = value.get("revision")
        return revision if isinstance(revision, int) else None

    def task_snapshot(self, task_id: str) -> dict[str, Any] | None:
        """Redacted TaskState projection: identity, revision, status, session,
        counts and domain-state KEY NAMES only.  Facts values, prompts and raw
        payloads are never returned."""
        key = self._require_owned_key(f"task-state:{task_id}", owner_scope=task_id)
        raw = self._client.get(key)
        if not raw:
            return None
        try:
            value = json.loads(raw)
        except (TypeError, json.JSONDecodeError):
            return None
        if not isinstance(value, Mapping):
            return None
        domain = value.get("domainState")
        return {
            "taskId": value.get("taskId"),
            "sessionId": value.get("sessionId"),
            "status": value.get("status"),
            "revision": value.get("revision"),
            "factCount": len(value.get("facts") or []),
            "constraintCount": len(value.get("constraints") or []),
            "pendingQuestionCount": len(value.get("pendingQuestions") or []),
            "domainStateKeys": sorted(domain.keys()) if isinstance(domain, Mapping) else [],
            "factsSha256": sha256_text(canonical_bytes(value.get("facts") or [])),
            "domainStateSha256": sha256_text(canonical_bytes(domain or {})),
        }

    def session_tasks(self, session_id: str) -> list[str]:
        key = self._require_owned_key(
            f"task-state-session:{session_id}:tasks", owner_scope=session_id
        )
        tasks = self._client.zrange(key, 0, -1)
        return [str(item) for item in tasks]

    def cursor(self, task_id: str) -> dict[str, Any] | None:
        key = self._require_owned_key(f"graph-v2:cursor:{task_id}", owner_scope=task_id)
        raw = self._client.get(key)
        if not raw:
            return None
        try:
            value = json.loads(raw)
        except (TypeError, json.JSONDecodeError):
            return None
        return value if isinstance(value, Mapping) else None

    # -- durable checkpoints -------------------------------------------------

    def latest_checkpoint(self, thread_id: str) -> tuple[str | None, str | None]:
        """Return ``(checkpoint_ref, checkpoint_sha256)`` for a thread.

        ``checkpoint_ref`` is the server's real latest checkpoint id (the
        ``:latest`` pointer).  ``checkpoint_sha256`` is the runner-computed
        SHA-256 of the raw stored envelope JSON (64-hex, schema-valid).  The
        saver's own integrity digest is ``sha256(payload)[:16]`` (16-hex) and
        is disclosed separately in the manifest; the schema's 64-hex field
        cannot carry it, so the runner hashes the whole server-owned envelope.
        """
        self._require_owned_key(f"graph-v2:cp:{thread_id}:x", owner_scope=thread_id)
        latest_key = f"graph-v2:cp:{thread_id}::latest"
        latest_id = self._client.get(latest_key)
        if not latest_id:
            return None, None
        cp_key = f"graph-v2:cp:{thread_id}::cp:{latest_id}"
        raw = self._client.get(cp_key)
        if not raw:
            return None, None
        return str(latest_id), sha256_text(raw.encode("utf-8"))

    def checkpoint_count(self, thread_id: str) -> int:
        self._require_owned_key(f"graph-v2:cp:{thread_id}:x", owner_scope=thread_id)
        count = 0
        for _ in self._client.scan_iter(
            match=f"graph-v2:cp:{thread_id}::cp:*", count=200
        ):
            count += 1
        return count

    # -- server trace records -------------------------------------------------

    def trace_record(self, run_id: str, *, owner_task_id: str, owner_session_id: str) -> dict[str, Any] | None:
        """Read the server-owned trace record for a run_id, but ONLY if it
        belongs to the supplied owned task/session.  Returns a redacted
        projection (finalAction, degraded, failureCode, taskId, sessionId,
        graphV2Events route/error/checkpointHash) — never prompts or payloads."""
        key = self._require_owned_key(f"agent-run-trace:{run_id}", owner_scope=run_id)
        raw = self._client.get(key)
        if not raw:
            return None
        try:
            value = json.loads(raw)
        except (TypeError, json.JSONDecodeError):
            return None
        if not isinstance(value, Mapping):
            return None
        record_task = value.get("taskId")
        record_session = value.get("sessionId")
        # REPAIR-005 Repair 1: the stored trace MUST be the SAME run that was
        # requested — a trace record that drifted to another runId is not
        # evidence of the current run and fails closed.
        if str(value.get("runId") or "") != str(run_id):
            raise RedisEvidenceError(
                f"refusing trace {run_id!r}: stored runId {value.get('runId')!r} "
                f"!= requested runId {run_id!r} (wrong-run trace)"
            )
        if record_task != owner_task_id or (owner_session_id and record_session != owner_session_id):
            raise RedisEvidenceError(
                f"refusing trace {run_id!r}: owner task/session mismatch "
                f"({record_task!r}/{record_session!r} vs owned "
                f"{owner_task_id!r}/{owner_session_id!r})"
            )
        events = []
        for event in value.get("graphV2Events") or []:
            if not isinstance(event, Mapping):
                continue
            events.append(
                {
                    "node": event.get("nodeName"),
                    "phase": event.get("phase"),
                    "route": event.get("routeDecision"),
                    "errorCode": event.get("errorCode"),
                    "checkpointHash": event.get("checkpointHash"),
                    "revisionBefore": event.get("revisionBefore"),
                    "revisionAfter": event.get("revisionAfter"),
                }
            )
        return {
            "runId": value.get("runId"),
            "taskId": value.get("taskId"),
            "sessionId": value.get("sessionId"),
            "finalAction": value.get("finalAction"),
            "degraded": bool(value.get("degraded")),
            "degradedReasons": value.get("degradedReasons") or [],
            "error": value.get("error"),
            "taskRevisionBefore": value.get("taskRevisionBefore"),
            "taskRevisionAfter": value.get("taskRevisionAfter"),
            "graphV2Events": events,
        }

    def read_owned_thread(self, task_id: str, run_id: str, *, session_id: str) -> str | None:
        """Read back a thread only when BOTH server-owned witnesses agree.

        REPAIR-006 removes the old marker-or-cursor fallback.  TaskState owner,
        ``v2RunMarker`` and ``graph-v2:cursor`` must all bind the same
        task/session/run/thread/owner hash.  The cursor revision is the earlier
        marker-write revision, so it must be a positive non-bool integer no
        greater than the current TaskState revision.  Missing, malformed or
        drifted witnesses return ``None``.  The owned-shape guard still runs
        before either of the two bounded Redis reads.
        """
        task_id, session_id, _, run_id = _require_owned_quad(
            task_id=task_id,
            session_id=session_id,
            thread_id=f"v2-task:{task_id}:{run_id}",
            run_id=run_id,
        )
        expected = f"v2-task:{task_id}:{run_id}"
        state_key = self._require_owned_key(f"task-state:{task_id}", owner_scope=task_id)
        cursor_key = self._require_owned_key(
            f"graph-v2:cursor:{task_id}", owner_scope=task_id
        )
        raw_state = self._client.get(state_key)
        raw_cursor = self._client.get(cursor_key)
        try:
            value = json.loads(raw_state) if raw_state else None
            cursor = json.loads(raw_cursor) if raw_cursor else None
        except (TypeError, json.JSONDecodeError):
            return None
        if not isinstance(value, Mapping) or not isinstance(cursor, Mapping):
            return None
        if value.get("taskId") != task_id or value.get("sessionId") != session_id:
            return None
        state_revision = value.get("revision")
        cursor_revision = cursor.get("revision")
        if (
            type(state_revision) is not int
            or state_revision <= 0
            or type(cursor_revision) is not int
            or cursor_revision <= 0
            or cursor_revision > state_revision
        ):
            return None
        domain = value.get("domainState")
        marker = domain.get("v2RunMarker") if isinstance(domain, Mapping) else None
        if not isinstance(marker, Mapping):
            return None
        owner_hash = session_owner_hash(session_id)
        marker_matches = (
            marker.get("runId") == run_id
            and marker.get("threadId") == expected
            and marker.get("sessionOwnerHash") == owner_hash
        )
        cursor_matches = (
            cursor.get("runId") == run_id
            and cursor.get("threadId") == expected
            and cursor.get("sessionOwnerHash") == owner_hash
        )
        return expected if marker_matches and cursor_matches else None

    def retrieval_channel_projection(
        self,
        task_id: str,
        *,
        session_id: str,
        thread_id: str,
        run_id: str,
    ) -> dict[str, Any]:
        """REPAIR-004 + REPAIR-005: read-only MINIMAL projection of the task-
        owned persisted ``stepExecutionResults`` — ONLY the CURRENT-RUN
        ``search_products`` tool's identity (taskId/planId/stepId/toolName)
        plus the SAFE per-channel ``retrievalTrace.channels`` status/count.
        Raw facts, prompts, candidate IDs, fused pools, evidence and private
        truth are NEVER returned.

        REPAIR-005: the task/session/thread/run FOUR-WAY relation is verified
        BEFORE any Redis I/O (``_require_owned_quad``), so a foreign identity
        is refused with zero reads (the recording-fake test proves 0 GET).  After
        the read, the SERVER-OWNED same-run markers are verified: ``v2RunMarker``
        (runId/threadId) proves the persisted thread is the current run's, and
        ``v2ExecReceipt`` (runId/planId/stepId/revision) proves the current run
        actually executed a step.  Only a ``search_products`` whose task/plan/step
        matches the owned task + v2ExecReceipt plan/step, is technically
        successful AND has a trace-ok ToolTrace can attest; historical or foreign
        step executions never contribute.
        """
        task_id, session_id, thread_id, run_id = _require_owned_quad(
            task_id=task_id, session_id=session_id, thread_id=thread_id, run_id=run_id
        )
        key = self._require_owned_key(f"task-state:{task_id}", owner_scope=task_id)
        raw = self._client.get(key)
        if not raw:
            return {
                "present": False,
                "searchProductCalls": [],
                "runId": run_id,
                "reason": "task-state missing (no persisted step execution)",
            }
        try:
            value = json.loads(raw)
        except (TypeError, json.JSONDecodeError):
            return {
                "present": False,
                "searchProductCalls": [],
                "runId": run_id,
                "reason": "task-state unparseable",
            }
        if not isinstance(value, Mapping):
            return {
                "present": False,
                "searchProductCalls": [],
                "runId": run_id,
                "reason": "task-state malformed",
            }
        record_task = value.get("taskId")
        record_session = value.get("sessionId")
        if record_task != task_id or (session_id and record_session != session_id):
            raise RedisEvidenceError(
                f"refusing task-state {task_id!r}: owner task/session mismatch "
                f"({record_task!r}/{record_session!r} vs owned "
                f"{task_id!r}/{session_id!r})"
            )
        domain = value.get("domainState")
        if not isinstance(domain, Mapping):
            return {
                "present": False,
                "searchProductCalls": [],
                "runId": run_id,
                "reason": "domainState missing",
            }
        # REPAIR-005: server-owned same-run markers.  The persisted thread must
        # be the CURRENT run's thread (v2RunMarker) and the persisted execution
        # must be the CURRENT run's step (v2ExecReceipt); a foreign or historical
        # run can never borrow them.
        marker = domain.get("v2RunMarker")
        if not isinstance(marker, Mapping):
            raise RedisEvidenceError(
                f"refusing task-state {task_id!r}: no server-owned v2RunMarker "
                "(current-run thread not persisted)"
            )
        marker_run = str(marker.get("runId") or "")
        marker_thread = str(marker.get("threadId") or "")
        marker_owner = str(marker.get("sessionOwnerHash") or "")
        expected_owner = session_owner_hash(session_id)
        if (
            marker_run != run_id
            or marker_thread != thread_id
            or marker_owner != expected_owner
        ):
            raise RedisEvidenceError(
                f"refusing task-state {task_id!r}: v2RunMarker "
                "run/thread/sessionOwnerHash drift"
            )
        receipt = domain.get("v2ExecReceipt")
        if not isinstance(receipt, Mapping):
            raise RedisEvidenceError(
                f"refusing task-state {task_id!r}: no server-owned v2ExecReceipt "
                "(current-run execution not persisted)"
            )
        receipt_run = str(receipt.get("runId") or "")
        receipt_plan = str(receipt.get("planId") or "")
        receipt_step = str(receipt.get("stepId") or "")
        claimed_revision = receipt.get("stateRevision")
        receipt_projection = domain.get("v2ExecReceiptProjection")
        receipt_revision = (
            receipt_projection.get("projectionRevision")
            if isinstance(receipt_projection, Mapping)
            else None
        )
        if (
            receipt_run != run_id
            or not receipt_plan
            or not receipt_step
            or type(claimed_revision) is not int
            or claimed_revision <= 0
            or type(receipt_revision) is not int
            or receipt_revision <= 0
            or receipt_revision != claimed_revision + 5
        ):
            raise RedisEvidenceError(
                f"refusing task-state {task_id!r}: v2ExecReceipt "
                f"run/plan/step/stateRevision/projectionRevision drift "
                f"({receipt_run!r}/{receipt_plan!r}/{receipt_step!r}/"
                f"{claimed_revision!r}/{receipt_revision!r} vs owned {run_id!r})"
            )
        task_revision = value.get("revision")
        if (
            type(task_revision) is not int
            or task_revision <= 0
            or task_revision != receipt_revision + 1
        ):
            raise RedisEvidenceError(
                f"refusing task-state {task_id!r}: completion revision chain "
                f"drift (task={task_revision!r}, receipt={receipt_revision!r})"
            )
        validation = domain.get("validationResult")
        if not isinstance(validation, Mapping):
            raise RedisEvidenceError(
                f"refusing task-state {task_id!r}: validationResult missing"
            )
        validator_based = validation.get("basedOnRevision")
        validator_task_matched = validation.get("taskId") == task_id
        validator_plan_matched = validation.get("planId") == receipt_plan
        validator_outcome = validation.get("outcome")
        if (
            type(validator_based) is not int
            or validator_based != receipt_revision
            or not validator_task_matched
            or not validator_plan_matched
            or validator_outcome != "passed"
        ):
            raise RedisEvidenceError(
                f"refusing task-state {task_id!r}: validator completion witness drift"
            )
        step_results = validation.get("stepResults")
        matching_validation_steps = [
            item
            for item in step_results
            if isinstance(item, Mapping) and item.get("stepId") == receipt_step
        ] if isinstance(step_results, list) else []
        validator_step_matched = len(matching_validation_steps) == 1
        validator_step_satisfied = (
            validator_step_matched
            and matching_validation_steps[0].get("outcome") == "satisfied"
        )
        if not validator_step_satisfied:
            raise RedisEvidenceError(
                f"refusing task-state {task_id!r}: validator step witness drift"
            )
        active_plan = value.get("activePlan")
        active_plan_matched = (
            isinstance(active_plan, Mapping)
            and active_plan.get("planId") == receipt_plan
        )
        active_plan_completed = (
            active_plan_matched and active_plan.get("status") == "completed"
        )
        plan_steps = active_plan.get("steps") if active_plan_matched else None
        matching_plan_steps = [
            item
            for item in plan_steps
            if isinstance(item, Mapping) and item.get("stepId") == receipt_step
        ] if isinstance(plan_steps, list) else []
        active_plan_step_matched = (
            len(matching_plan_steps) == 1
            and matching_plan_steps[0].get("status") == "executed"
        )
        if not active_plan_completed or not active_plan_step_matched:
            raise RedisEvidenceError(
                f"refusing task-state {task_id!r}: activePlan completion witness drift"
            )
        completion_projection = {
            "taskStateRevision": task_revision,
            "execReceiptRevision": receipt_revision,
            "execReceiptClaimedRevision": claimed_revision,
            "validatorBasedOnRevision": validator_based,
            "validatorOutcome": validator_outcome,
            "validatorTaskMatched": validator_task_matched,
            "validatorPlanMatched": validator_plan_matched,
            "validatorStepMatched": validator_step_matched,
            "validatorStepOutcomeSatisfied": validator_step_satisfied,
            "activePlanMatched": active_plan_matched,
            "activePlanCompleted": active_plan_completed,
            "activePlanStepMatched": active_plan_step_matched,
        }
        history = domain.get("stepExecutionResults")
        if not isinstance(history, list):
            return {
                "present": True,
                "searchProductCalls": [],
                "runId": run_id,
                "v2RunMarkerMatched": True,
                "v2ExecReceipt": {
                    "runId": run_id,
                    "planId": receipt_plan,
                    "stepId": receipt_step,
                    "revision": receipt_revision,
                },
                **completion_projection,
                "reason": "stepExecutionResults missing",
            }
        calls: list[dict[str, Any]] = []
        for item in history:
            if not isinstance(item, Mapping):
                continue
            if str(item.get("toolName") or "") != "search_products":
                continue
            # REPAIR-005: ONLY the current-run matching task/plan/step can
            # attest.  Historical / foreign step executions (other task, other
            # plan, other step) are excluded — they never contribute to the
            # current-run attestation.
            if str(item.get("taskId") or "") != task_id:
                continue
            if str(item.get("planId") or "") != receipt_plan or str(item.get("stepId") or "") != receipt_step:
                continue
            if str(item.get("outcome") or "") != "tool_succeeded":
                continue
            trace = item.get("toolTrace")
            if not isinstance(trace, Mapping) or not bool(trace.get("ok")):
                continue
            detail = trace.get("detail")
            channels: dict[str, dict[str, Any]] = {}
            if isinstance(detail, Mapping):
                retrieval_trace = detail.get("retrievalTrace")
                if isinstance(retrieval_trace, Mapping):
                    raw_channels = retrieval_trace.get("channels")
                    if isinstance(raw_channels, Mapping):
                        for channel_name, channel in raw_channels.items():
                            if not isinstance(channel, Mapping):
                                continue
                            status = channel.get("status")
                            if not isinstance(status, str) or not status:
                                continue
                            channels[str(channel_name)] = {
                                "status": status,
                                "count": channel.get("count"),
                            }
            calls.append(
                {
                    "taskId": item.get("taskId"),
                    "planId": item.get("planId"),
                    "stepId": item.get("stepId"),
                    "toolName": "search_products",
                    "channels": channels,
                }
            )
        return {
            "present": True,
            "searchProductCalls": calls,
            "runId": run_id,
            "v2RunMarkerMatched": True,
            "v2ExecReceipt": {
                "runId": run_id,
                "planId": receipt_plan,
                "stepId": receipt_step,
                "revision": receipt_revision,
            },
            **completion_projection,
        }

    def terminal_receipt(
        self, task_id: str, run_id: str, proposal_hash: str, session_id: str
    ) -> dict[str, Any] | None:
        """Read the identity-validated terminal response receipt (the exact
        answer string the server stored for an idempotent replay)."""
        identity = "\x00".join((task_id, run_id, proposal_hash)).encode("utf-8")
        digest = hashlib.sha256(identity).hexdigest()
        key = self._require_owned_key(f"graph-v2:terminal:{digest}", owner_scope=run_id)
        raw = self._client.get(key)
        if not raw:
            return None
        try:
            value = json.loads(raw)
        except (TypeError, json.JSONDecodeError):
            return None
        if not isinstance(value, Mapping):
            return None
        if (
            value.get("taskId") != task_id
            or value.get("runId") != run_id
            or value.get("threadId") != f"v2-task:{task_id}:{run_id}"
            or value.get("proposalHash") != proposal_hash
            or value.get("sessionOwnerHash") != session_owner_hash(session_id)
        ):
            raise RedisEvidenceError(
                f"refusing terminal receipt for {run_id!r}: identity mismatch"
            )
        return {
            "answer": value.get("answer"),
            "proposalHash": value.get("proposalHash"),
            "answerHash": value.get("answerHash"),
            "appliedRevision": value.get("appliedRevision"),
        }


def session_owner_hash(session_id: str) -> str:
    return hashlib.sha256(session_id.encode("utf-8")).hexdigest()[:16]


def sha256_text(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def proposal_hash(task_id: str, question: str, revision: int) -> str:
    """Deterministic short hash over the visible question + server identity.

    Mirrors ``agent/app/graph/nodes/clarification.py::_proposal_hash`` so the
    runner can echo the exact server-owned ``proposalHash`` on resume using
    values already observed in the public response (taskId, pending question,
    TaskState revision) — no private file access needed.
    """
    canonical = json.dumps(
        {
            "taskId": task_id,
            "question": question,
            "revision": revision,
        },
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()[:16]


