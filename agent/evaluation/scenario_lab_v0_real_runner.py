def _iso_timestamp() -> str:
    """UTC ISO-8601 with +00:00 offset (no microseconds; stable across runs)."""
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "+00:00")


# Definitive private-truth markers for argv/cwd/env/path scanning.  Narrower
# than the record-leaf scan on purpose: "default" (which contains "fault" as a
# substring) must never trip a process-boundary check, while "oracle.private",
# "fault.private", "acceptableProductIds", "expectedTerminal..." and
