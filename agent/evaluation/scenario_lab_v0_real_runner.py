def is_port_free(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.settimeout(0.5)
        try:
            sock.bind(("127.0.0.1", port))
            return True
        except OSError:
            return False


def find_free_port(start: int = MIN_PORT, end: int = MAX_PORT) -> int:
    for port in range(start, end + 1):
        if is_port_free(port):
            return port
    raise RuntimeError(f"no free port in [{start}, {end}]")


class TaskOwnedServer:
    """A real uvicorn process this task spawned and therefore may stop/kill.

    Only processes created here (with a task-owned runtime dir, explicit
    argv/env/cwd) are ever terminated; the PID/commandline/port triple belongs
    to this task's ownership evidence.
    """

    def __init__(self, port: int, run_root: Path, env_overrides: Mapping[str, str]) -> None:
        self.port = port
        self.run_root = run_root
        self.env_overrides = dict(env_overrides)
        self.proc: subprocess.Popen | None = None
        self.stdout_log = run_root / f"server-{port}.stdout.log"
        self.stderr_log = run_root / f"server-{port}.stderr.log"

    @property
    def base_url(self) -> str:
        return f"http://127.0.0.1:{self.port}"

    def start(self) -> None:
        env = os.environ.copy()
        env.update(self.env_overrides)
        creationflags = subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0
        self.run_root.mkdir(parents=True, exist_ok=True)
        with open(self.stdout_log, "w", encoding="utf-8") as stdout_fh, open(
            self.stderr_log, "w", encoding="utf-8"
        ) as stderr_fh:
            self.proc = subprocess.Popen(
                [
                    sys.executable,
                    "-m",
                    "uvicorn",
                    "agent.app.main:app",
                    "--host",
                    "127.0.0.1",
                    "--port",
                    str(self.port),
                    "--log-level",
                    "warning",
                ],
                cwd=str(REPO_ROOT),
                env=env,
                stdout=stdout_fh,
                stderr=stderr_fh,
                creationflags=creationflags,
            )

    def wait_health(self, timeout_seconds: float = 90.0) -> bool:
        import httpx

        deadline = time.time() + timeout_seconds
        while time.time() < deadline:
            if self.proc is not None and self.proc.poll() is not None:
                return False
            try:
                response = httpx.get(f"http://127.0.0.1:{self.port}/docs", timeout=3.0)
                if response.status_code < 500:
                    return True
            except Exception:  # noqa: BLE001 - server still booting
                pass
            time.sleep(1.0)
        return False

    def stop(self) -> None:
        if self.proc is None:
            return
        if self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                self.proc.kill()
                self.proc.wait(timeout=10)
        self.proc = None

    def kill_hard(self) -> None:
        """Controlled kill of OUR OWN process — the INF-001 restart trigger."""
        if self.proc is None:
            return
        if self.proc.poll() is None:
            self.proc.kill()
            try:
                self.proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                pass
        self.proc = None


