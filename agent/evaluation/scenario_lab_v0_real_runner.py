def _require_task_identity(body: dict[str, Any] | None) -> tuple[str, str, str] | None:
    """Return (task_id, run_id, thread_id) from a real response or None."""
    if not body:
        return None
    norm = normalize_body(body)
    run_id = norm["run_id"] or (norm["trace_summary"] or {}).get("runId")
    task_state = norm["task_state"]
    task_id = task_state.get("taskId") if isinstance(task_state, Mapping) else None
    if not task_id or not run_id:
        return None
    return str(task_id), str(run_id), f"v2-task:{task_id}:{run_id}"


def _receipt_identity_mismatch(
    fixture_receipt: FixtureReceipt | None,
    task_id: str,
    run_id: str,
    thread_id: str,
) -> list[str]:
    """Return identity-drift descriptions, or [] when the observed
    (taskId/runId/threadId) EXACTLY match the signed fixture receipt.

    REPAIR-004 Repair 1c: the first real response's identity must exactly equal
    the receipt (taskId, threadId and the non-empty runId inside it).  Any
    drift is an explicit identity failure resolved BEFORE any kill / restart /
    second request / recovery ref.
    """
    if fixture_receipt is None:
        return []
    mismatches: list[str] = []
    if task_id != fixture_receipt.task_id:
        mismatches.append(f"taskId {task_id!r} != receipt {fixture_receipt.task_id!r}")
    if thread_id != fixture_receipt.thread_id:
        mismatches.append(
            f"threadId {thread_id!r} != receipt {fixture_receipt.thread_id!r}"
        )
    receipt_run_id = (
        fixture_receipt.thread_id.split(":")[2]
        if fixture_receipt.thread_id.count(":") == 2
        else ""
    )
    if run_id != receipt_run_id:
        mismatches.append(f"runId {run_id!r} != receipt {receipt_run_id!r}")
    return mismatches


def _parked_clarification(body: dict[str, Any] | None) -> tuple[str | None, int | None, str | None]:
    """Return (question, revision, proposal_hash) from a real parked
    clarification response, or (None, None, None) if none was parked."""
    norm = normalize_body(body)
    task_state = norm["task_state"]
    if not isinstance(task_state, Mapping):
        return None, None, None
    questions = [q for q in (task_state.get("pendingQuestions") or []) if isinstance(q, str) and q]
    task_id = task_state.get("taskId")
    revision = task_state.get("revision")
    if not questions or not task_id or not isinstance(revision, int):
        return None, None, None
    return questions[0], revision, proposal_hash(str(task_id), questions[0], revision)


